#!/usr/bin/env python3
"""Generate tokens.css from tokens.json (DTCG-style, CSS bindings in $extensions.nu.css).

Usage: python scripts/build-tokens.py [--check]
  --check  exit 1 if tokens.css is out of date instead of writing it.
Token references like {color.primitive.black} become var(--black).
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "/* Generated by scripts/build-tokens.py. Edit tokens.json, then rebuild. */\n"

def leaves(node, path=()):
    if isinstance(node, dict):
        if "$value" in node:
            yield ".".join(path), node
        else:
            for key, child in node.items():
                if not key.startswith("$") and key != "meta":
                    yield from leaves(child, path + (key,))

def main():
    data = json.loads((ROOT / "tokens.json").read_text())
    tokens = dict(leaves(data))
    css_name = lambda t: t["$extensions"]["nu"]["css"]

    def dim(v):
        return f'{v["value"]}{v["unit"]}'

    def ref_or(value, fmt=str):
        if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            return f"var({css_name(tokens[value[1:-1]])})"
        return fmt(value)

    def render(token):
        kind, value = token["$type"], token["$value"]
        if kind == "dimension":
            return ref_or(value, dim)
        if kind == "fontFamily":
            fallback = "ui-monospace, monospace" if "Mono" in value else "system-ui, sans-serif"
            return f'"{value}", {fallback}'
        if kind == "shadow":
            parts = [ref_or(value["offsetX"], dim), ref_or(value["offsetY"], dim),
                     ref_or(value["blur"], dim), ref_or(value["spread"], dim),
                     ref_or(value["color"])]
            return " ".join(parts)
        return ref_or(value)  # color, fontWeight, ...

    # Shadows are re-declared on .nu-root as well as :root. A var() inside a custom
    # property is resolved where it is declared, so without this a theme that sets
    # --nu-border on <main class="nu-root my-store"> would not reach the shadows.
    base = [t for t in tokens.values() if t["$type"] != "shadow"]
    shadows = [t for t in tokens.values() if t["$type"] == "shadow"]
    lines = [HEADER, ":root {\n"]
    lines += [f"  {css_name(t)}: {render(t)};\n" for t in base]
    lines.append("}\n")
    lines.append(":root, .nu-root {\n")
    lines += [f"  {css_name(t)}: {render(t)};\n" for t in shadows]
    lines.append("}\n")
    out = "".join(lines)

    target = ROOT / "tokens.css"
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == out else 1)
    target.write_text(out)
    print(f"Wrote {target.name}: {len(tokens)} tokens")

if __name__ == "__main__":
    main()
